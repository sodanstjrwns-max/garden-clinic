export const osanCardByKey = (key: string) => OSAN_CARDS.find((c) => c.key === key)

/** 이미지 경로 — og(1200×630 jpg), body(1200×800 webp), card(600×600 webp) */
export function osanCardImg(c: OsanCard, kind: 'og' | 'body' | 'card'): string {
  const base = `/static/img/osan/${c.img}`
  return kind === 'og' ? `${base}-1200x630.jpg` : kind === 'body' ? `${base}-1200.webp` : `${base}-600.webp`
}

/** 홈 ItemList JSON-LD — 화면 카드 그리드와 1:1 */
export function osanItemListSchema(id: string) {
  return {
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    '@id': id,
    name: '오산 한의원 진료별 안내',
    numberOfItems: OSAN_CARDS.length,
    itemListElement: OSAN_CARDS.map((c, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: c.name,
      url: `${CLINIC.domain}${c.path}`,
      image: `${CLINIC.domain}${osanCardImg(c, 'og')}`,
    })),
  }
}

